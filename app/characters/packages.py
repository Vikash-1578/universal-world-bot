"""Portable asset packages (.uwpkg = zip): manifest.json + files, every file SHA-256 checked on import.

Import is defensive: size limits, no absolute paths / '..' (zip-slip), only PNG/JPG files, schema check,
checksum check — a bad package is rejected completely, nothing is half-imported.
"""
from __future__ import annotations

import io
import json
import time
import zipfile
from pathlib import Path

from app.characters.service import LibraryService
from app.core.errors import InvalidInput
from app.storage.files import sha256_bytes

SCHEMA = 1
MAX_PKG = 80 * 1024 * 1024
MAX_FILES = 60
ALLOWED_EXT = (".png", ".jpg", ".jpeg")


def export_item(lib: LibraryService, item_id: str) -> tuple[str, bytes]:
    it = lib.get(item_id)
    files = {}
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for role, f in it["files"].items():
            p = lib.file_path(it, role)
            if p is None:
                continue
            data = p.read_bytes()
            name = f"files/{role.replace(':', '__')}{p.suffix}"
            z.writestr(name, data)
            files[role] = {"file": name, "sha256": sha256_bytes(data)}
        manifest = {"schema": SCHEMA, "app": "universal-world-bot", "exported_at": time.time(),
                    "item": {"id": it["id"], "kind": it["kind"], "name": it["name"], "category": it["category"],
                             "version": it["version"], "qc_status": it["qc_status"]},
                    "profile": it["profile"], "files": files}
        z.writestr("manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))
    return f"{it['id']}_v{it['version']}.uwpkg.zip", buf.getvalue()


def import_package(lib: LibraryService, data: bytes) -> dict:
    if len(data) > MAX_PKG:
        raise InvalidInput("Package bahut bada hai.")
    try:
        z = zipfile.ZipFile(io.BytesIO(data))
    except zipfile.BadZipFile as e:
        raise InvalidInput("Ye zip file nahi hai.") from e
    names = z.namelist()
    if len(names) > MAX_FILES + 1:
        raise InvalidInput("Package me bahut saari files hain.")
    for n in names:
        if n.startswith(("/", "\\")) or ".." in Path(n).parts or ":" in n:
            raise InvalidInput("Package me galat file path hai (security).")
    if sum(i.file_size for i in z.infolist()) > MAX_PKG * 2:
        raise InvalidInput("Package khulne par bahut bada hai.")
    try:
        manifest = json.loads(z.read("manifest.json").decode("utf-8"))
    except (KeyError, ValueError) as e:
        raise InvalidInput("manifest.json nahi mila / kharab hai.") from e
    if manifest.get("schema") != SCHEMA or manifest.get("app") != "universal-world-bot":
        raise InvalidInput("Ye package is bot ka nahi hai ya naye version ka hai.")
    item = manifest.get("item") or {}
    kind = item.get("kind")
    files = manifest.get("files") or {}
    blobs: dict[str, bytes] = {}
    for role, f in files.items():
        name = f.get("file", "")
        if name not in names or not name.lower().endswith(ALLOWED_EXT):
            raise InvalidInput(f"File {name} nahi mili ya allowed nahi hai.")
        blob = z.read(name)
        if sha256_bytes(blob) != f.get("sha256"):
            raise InvalidInput(f"File {name} kharab hai (checksum match nahi hua).")
        blobs[role] = blob
    new = lib.create_item(kind, item.get("name", "Imported"), manifest.get("profile") or {}, category=item.get("category", ""),
                          note=f"Package se import (asli v{item.get('version')})")
    try:
        for role in sorted(blobs):
            if role.endswith(":original") or role.startswith("reference:"):
                continue  # originals are regenerated by add_image; references are optional
            new, _ = lib.add_image(new["id"], role, blobs[role], source="package")
    except Exception:
        lib.db.execute("DELETE FROM library_items WHERE id = ?", (new["id"],))  # all or nothing
        raise
    return new
